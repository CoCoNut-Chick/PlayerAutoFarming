package com.autofarm.client.path;

/**
 * 「走到下一个落脚点之前，需要先对世界做点什么」。
 *
 * <p>有了它，寻路就不只是在<b>已有的</b>地形上找路，还可以<b>改地形</b>：
 * 把挡路的方块挖掉、在脚下垫一块方块。这也是自动农场能应付
 * 「田被围栏圈起来」「中间隔了条水渠」这类情况的关键。
 */
public enum PathAction {

    /** 那格本来就是空的，直接走过去 */
    WALK,

    /** 那格被方块堵住了，先挖掉再走 */
    MINE,

    /** 那格脚下没有支撑（悬空/沟壑），先垫一块方块再走 */
    PLACE
}
